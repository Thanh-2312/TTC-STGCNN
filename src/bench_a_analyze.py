"""A-bench analysis (experiments/A-bench/protocol.md): order effect per model and dataset, decisions A1-A3.

usage: python src/bench_a_analyze.py <out dir with <model>/<ds>/*.npz> <results prefix>
"""
import os, sys, glob, json
import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[:0] = [HERE, os.path.join(HERE, '..', 'colab', 'bench_a')]
from adapters import CLASS_D, CLASS_I  # noqa: E402

THR = 0.01  # m


def load(f):
    z = np.load(f)
    k = z['key']
    u, c = np.unique(k, return_counts=True)
    keep = np.isin(k, u[c == 1])                                          # windows whose key is not unique are dropped
    return {n: z[n][keep] for n in z.files}, int((~keep).sum())


def cell(d):
    ids = [load(f) for f in sorted(glob.glob(os.path.join(d, 'id_s*.npz')))]
    rs = [load(f) for f in sorted(glob.glob(os.path.join(d, 'r*_s0.npz')), key=lambda f: int(os.path.basename(f)[1:-7]))]
    if len(ids) < 5 or not rs or not os.path.exists(os.path.join(d, 'idrep_s0.npz')):
        return None
    rep = load(os.path.join(d, 'idrep_s0.npz'))
    common = set(ids[0][0]['key'])
    for z, _ in ids + rs + [rep]:
        common &= set(z['key'])
    common = np.array(sorted(common))

    def take(z):
        i = np.argsort(z['key'])
        z = {n: v[i] for n, v in z.items()}
        j = np.searchsorted(z['key'], common)
        return {n: v[j] for n, v in z.items()}
    ref, *noi = [take(z) for z, _ in ids]
    per = [take(z) for z, _ in rs]
    rep = take(rep[0])
    fin = lambda a, b, n='cen': np.linalg.norm(a[n][:, -1] - b[n][:, -1], axis=-1)
    # classification (amendment 1): noise-pinned outputs, re-indexed vs identity at seed 0, against a same-seed repeat
    pin = [fin(z, ref, 'pin').mean() for z in per]
    floor = float(fin(rep, ref, 'pin').mean())
    E = float(np.mean(pin) - floor)
    # descriptive: the released sampler (sample centroid), against its different-seed noise
    shift = [fin(z, ref).mean() for z in per]
    noise = [fin(z, ref).mean() for z in noi]
    ade_r, ade_s = np.mean([z['ade'].mean() for z in per]), np.mean([z['ade'].mean() for z in [ref] + noi])
    # fidelity: identity accuracy over all windows (duplicated keys included), mean of the 5 seeds
    seeds = [v for k, v in json.load(open(os.path.join(d, 'id.json')))['seeds'].items() if k.startswith('id_')]
    return dict(n=len(common), n_ref=len(ids[0][0]['key']), dup=ids[0][1], draws=len(rs),
                shift_pin=float(np.mean(pin)), shift_pin_min=float(np.min(pin)), floor=floor, E=E,
                dependent=bool(E >= THR and np.min(pin) > floor), invariant=bool(E < THR),
                shift=float(np.mean(shift)), noise=float(np.mean(noise)),
                dADE=float(ade_r / ade_s - 1), share05=float(np.mean([(fin(z, ref) > 0.5).mean() for z in per])),
                share05_pin=float(np.mean([(fin(z, ref, 'pin') > 0.5).mean() for z in per])),
                ADE=float(ade_s), FDE=float(np.mean([z['fde'].mean() for z in [ref] + noi])),
                n_all=seeds[0]['n'], ADE_all=float(np.mean([v['ade'] for v in seeds])),
                FDE_all=float(np.mean([v['fde'] for v in seeds])))



def main(OUT, RES):
    res = {}
    for d in sorted(glob.glob(os.path.join(OUT, '*', '*'))):
        m, ds = d.split(os.sep)[-2:]
        c = cell(d)
        if c:
            res.setdefault(m, {})[ds] = c

    dec = {}
    for m in CLASS_D:
        n = sum(v['dependent'] for v in res.get(m, {}).values())
        dec[m] = dict(cls='D', datasets=len(res.get(m, {})), dependent=n, holds=n >= 4)
    for m in CLASS_I:
        n = sum(v['invariant'] for v in res.get(m, {}).values())
        dec[m] = dict(cls='I', datasets=len(res.get(m, {})), invariant=n, holds=n == 5)
    pairs = [v['dADE'] for m in CLASS_D for v in res.get(m, {}).values()]
    A3 = dict(pairs=len(pairs), worse=int(sum(x > 0 for x in pairs)), holds=bool(pairs) and sum(x > 0 for x in pairs) >= 30)
    summary = dict(A1=all(dec[m]['holds'] for m in CLASS_D), A2=all(dec[m]['holds'] for m in CLASS_I), A3=A3,
                   missing=[m for m in CLASS_D + CLASS_I if len(res.get(m, {})) < 5])
    json.dump(dict(cells=res, models=dec, summary=summary), open(RES + '.json', 'w'), indent=1)

    L = ['# A-bench results (auto-generated by src/bench_a_analyze.py)', '',
         f"A1 (class D order-dependent on >= 4/5): {summary['A1']} · A2 (class I invariant on 5/5): {summary['A2']} · "
         f"A3 (ΔminADE20 > 0 in >= 30 of 60 class-D pairs): {A3['worse']}/{A3['pairs']} -> {A3['holds']}",
         f"Models with fewer than 5 datasets evaluated: {summary['missing'] or 'none'}", '',
         'Verdict from noise-pinned outputs (amendment 1); "released" columns use the authors\' samplers as published.', '',
         'minADE20 / minFDE20: matched windows (the comparison); "all": every window, for comparison with published tables.', '',
         '| model | class | ds | n | shift pinned (m) | floor (m) | E (m) | verdict | >0.5 m pinned | released shift (m) | '
         'released seed noise (m) | >0.5 m released | ΔminADE20 | minADE20 | minFDE20 | n all | minADE20 all | minFDE20 all |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for m in CLASS_D + CLASS_I:
        for ds, v in res.get(m, {}).items():
            verdict = 'dependent' if v['dependent'] else 'invariant' if v['invariant'] else 'unclear'
            L.append(f"| {m} | {dec[m]['cls']} | {ds} | {v['n']} | {v['shift_pin']:.3f} | {v['floor']:.4f} | {v['E']:.3f} | "
                     f"{verdict} | {100 * v['share05_pin']:.1f}% | {v['shift']:.3f} | {v['noise']:.3f} | "
                     f"{100 * v['share05']:.1f}% | {100 * v['dADE']:+.1f}% | {v['ADE']:.3f} | {v['FDE']:.3f} | "
                     f"{v['n_all']} | {v['ADE_all']:.3f} | {v['FDE_all']:.3f} |")
    L += ['', '| model | class | datasets | verdict count | prediction holds |', '|---|---|---|---|---|']
    L += [f"| {m} | {v['cls']} | {v['datasets']} | {v.get('dependent', v.get('invariant'))} | {v['holds']} |" for m, v in dec.items()]
    open(RES + '.md', 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print('\n'.join(L[:5]))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
